        <!-- ── SITE EVALUATION ───────────────────────────────────── -->
        <h2 id="site-evaluation">Start With a Septic Site Evaluation</h2>

        <p>
          A septic site evaluation is the starting point for any onsite wastewater system in Oregon. DEQ says that during a site evaluation, an onsite program specialist evaluates soil test pits in the proposed initial and replacement soil absorption areas, records soil and groundwater conditions, and checks for site constraints that require septic setbacks. DEQ also notes that a site evaluation does not guarantee approval of a specific system — it establishes whether the site can support an onsite wastewater system and under what conditions. A separate construction-installation permit is required if the site is approved.
        </p>
        <p>
          For off-grid land buyers in Eastern Oregon, this matters enormously: a site evaluation should happen before you fall in love with a house location. The best view on the property may not be the best place to build if the septic system cannot work there.
        </p>

        <ul>
          <li><strong>Soil test pits:</strong> Soil test pits are excavated in proposed drain field areas to evaluate soil texture, structure, depth to groundwater, and depth to restrictive layers like hardpan or bedrock. The results determine what type of system may be approved and how large the drain field needs to be.</li>
          <li><strong>Soil depth:</strong> Eastern Oregon soils vary widely. Some areas of Grant County have deep loamy soils well-suited to conventional drain fields. Others have shallow soils over basalt, fractured rock, or hardpan that severely limit drain field options. Soil depth directly determines what system types are possible.</li>
          <li><strong>Groundwater conditions:</strong> Seasonal high groundwater — even if not present year-round — affects drain field depth and system type. A field that is dry in August may have groundwater close to the surface in March. The site evaluation captures both soil conditions and seasonal groundwater indicators.</li>
          <li><strong>Slope and drainage:</strong> Slopes affect how effluent moves through the soil and whether pressure distribution is needed. Steep slopes can prevent conventional gravity drain fields. Flat areas with poor drainage can create seasonal saturation issues. Slope and drainage are both evaluated during the site visit.</li>
          <li><strong>Rock and hardpan:</strong> Shallow bedrock or hardpan layers are common on Eastern Oregon parcels in certain geologic zones. These layers prevent soil absorption of effluent and may require engineered alternatives — or may make a site unsuitable for an onsite system altogether.</li>
          <li><strong>Proposed drain field area:</strong> The site evaluation covers the area proposed for the initial drain field. The specialist evaluates whether conditions in that specific location meet DEQ's requirements for the proposed system type.</li>
          <li><strong>Replacement drain field area:</strong> A separate replacement area must also be evaluated. This area is held in reserve. Both the primary and replacement areas must be identified before the permit is issued.</li>
          <li><strong>Setbacks from wells, springs, streams, property lines, and structures:</strong> The site evaluation checks that proposed drain field areas maintain required setback distances from water sources, property boundaries, and existing structures. These setbacks may eliminate portions of the parcel from consideration.</li>
          <li><strong>Why this should happen before final home placement:</strong> The drain field location that the site evaluation approves may not align with where the homeowner initially planned to put the house. Running a site evaluation — even informally, before purchase — is one of the best investments a rural buyer can make.</li>
        </ul>

