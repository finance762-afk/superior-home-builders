        <!-- ── PERMITS FOR NEW BUILDS ─────────────────────────────── -->
        <h2 id="new-permits">Septic Permits for New Off-Grid Homes</h2>

        <p>
          For a new off-grid home in Eastern Oregon, septic approval should be treated as part of the build plan — not a side task. DEQ says septic permits are required for new installations, alterations, and repairs, and that an onsite program specialist reviews the application to confirm the site evaluation conditions and rule requirements are met before issuing the permit. The permit cannot be issued until the site has been evaluated, a system design meeting DEQ requirements has been prepared, and the application has been reviewed and approved.
        </p>

        <ul>
          <li><strong>New septic installation permit:</strong> The permit covers new system installation on a property that has no existing permitted system. The application requires the site evaluation report, a system design, and documentation that the proposed location meets setback requirements.</li>
          <li><strong>Site evaluation report conditions:</strong> Site evaluations often come with conditions — soil conditions that limit system depth, setbacks that restrict location options, or system type requirements based on soil percolation. The permit application must address each condition from the site evaluation.</li>
          <li><strong>Septic design:</strong> A system design specifies the tank size, distribution system, drain field dimensions and layout, and any additional treatment components required by site conditions. The design must be prepared by a licensed onsite systems designer where required by Oregon rules.</li>
          <li><strong>Licensed installers:</strong> Oregon requires that onsite wastewater systems be installed by licensed contractors in most circumstances. The county's environmental health office can confirm installer licensing requirements for the specific system type and location.</li>
          <li><strong>Inspection before covering:</strong> The installed system must be inspected by a DEQ or county program specialist before being covered with soil. A system covered before inspection cannot be verified as compliant and may need to be uncovered — a costly and disruptive problem.</li>
          <li><strong>As-built documentation:</strong> After installation and inspection, an as-built drawing must be recorded with the county. This document shows exactly what was installed and where. It becomes part of the property's permanent record and is required for future permit applications, property sales, and system modifications.</li>
          <li><strong>Final approval:</strong> After inspection and as-built recording, the permit is closed with final approval. Only at this point is the system legally authorized for use. Occupying a home before the septic system is approved creates DEQ compliance issues.</li>
        </ul>

        <div class="highlight-box reveal-up">
          <div class="highlight-box__icon" aria-hidden="true">
            <i data-lucide="file-check"></i>
          </div>
          <div class="highlight-box__body">
            <strong>For a new off-grid home, septic approval should be treated as part of the build plan, not a side task.</strong>
            <p>The site evaluation, system design, permit application, installation, inspection, and as-built recording are all steps in a process that takes time and must happen in sequence. Scheduling this process early — before the home is framed — keeps the project on timeline and avoids holding up final occupancy.</p>
          </div>
