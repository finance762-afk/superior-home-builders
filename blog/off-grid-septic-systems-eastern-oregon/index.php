        <!-- ── SYSTEM TYPES ───────────────────────────────────────── -->
        <h2 id="system-types">Standard Septic vs Alternative Septic Systems</h2>

        <p>
          Not every rural property can use the same septic design. Soil depth, slope, groundwater, setbacks, and available space all affect what type of system may be allowed. Understanding the range of system options helps homeowners have realistic conversations with their designer and builder about what is possible on a specific parcel — and what the cost and maintenance implications of each option look like.
        </p>

        <ul>
          <li><strong>Conventional gravity system:</strong> The most common and least expensive type. A gravity-fed drain field distributes effluent from the septic tank by gravity flow through perforated distribution pipes into the surrounding soil. Requires adequate soil depth, acceptable percolation rate, and enough flat-to-gently-sloped area away from groundwater and setback constraints.</li>
          <li><strong>Pressure distribution system:</strong> Uses a pump to distribute effluent more evenly across the drain field. This is common on sites where soil conditions or slope would prevent adequate distribution by gravity alone. Adds a pump and pump chamber to the system, which requires maintenance and occasional pump replacement.</li>
          <li><strong>Sand filter system:</strong> Provides additional treatment of effluent through a sand media bed before it reaches the soil absorption area. Used when soil conditions are poor — shallow depth, slow percolation, or proximity to groundwater. More expensive to install and may have a larger footprint than a conventional system.</li>
          <li><strong>Alternative treatment technologies (ATU):</strong> Engineered treatment systems that provide a higher level of effluent treatment before soil dispersal. Used on sites that cannot support conventional or pressure distribution systems due to severe constraints. Significantly more expensive to install and require ongoing maintenance contracts. Sometimes the only option on a challenging site.</li>
          <li><strong>Holding tanks (where allowed):</strong> A holding tank stores sewage without treating it and must be pumped regularly. DEQ allows holding tanks in limited circumstances — typically as a temporary measure or for extremely constrained sites with no practical alternative. For a full-time residence, the cost of regular pumping makes holding tanks impractical as a permanent solution.</li>
          <li><strong>Composting toilets (where allowed):</strong> A composting toilet reduces or eliminates the blackwater portion of the wastewater stream. Where allowed by DEQ and the county, this may reduce the size of the required onsite system. However, graywater from showers, sinks, laundry, and kitchen drains still needs to be handled — and the rules around that vary. Composting toilets are covered in more detail in the next section.</li>
        </ul>

        <!-- ── COMPOSTING TOILETS ─────────────────────────────────── -->
        <h2 id="composting">Composting Toilets and Graywater: Be Careful With Assumptions</h2>

        <p>
          Composting toilets appear frequently in off-grid planning discussions as a way to reduce or eliminate the need for a conventional septic system. The reality is more complicated. A composting toilet may reduce the blackwater portion of the waste stream, but it does not automatically solve every wastewater issue — and designing around internet advice about composting toilets or graywater without confirming current rules with Oregon DEQ and your county can lead to serious problems.
        </p>

        <ul>
          <li><strong>Composting toilets are not a free pass around wastewater rules:</strong> A composting toilet may be permissible in certain Oregon situations, but it does not eliminate the need to address graywater. And the rules governing composting toilet use in conjunction with graywater systems vary by county and situation. Do not assume that purchasing a composting toilet resolves the wastewater permitting question.</li>
          <li><strong>Graywater is still regulated:</strong> Showers, sinks, laundry, and kitchen drains generate graywater — water that does not contain toilet waste but still contains soap, food particles, bacteria, and other contaminants. Oregon regulates graywater disposal. Even where separate graywater systems are allowed, they typically require a permit and must meet specific standards.</li>
          <li><strong>Sinks, showers, and laundry create substantial wastewater volume:</strong> A household of four generates significant daily graywater volume from showers, laundry, and kitchen use alone. A system sized only for reduced-blackwater conditions must still handle this volume safely and legally.</li>
          <li><strong>Local approval matters more than general rules:</strong> Oregon's graywater rules allow county programs some flexibility in how they administer approvals. What is possible in one county may not be possible in another. Grant County and surrounding Eastern Oregon counties each administer their programs somewhat differently. Confirm with your specific county's environmental health office.</li>
          <li><strong>Do not design around internet advice:</strong> Online forums about off-grid living frequently contain advice about composting toilets and graywater systems that is outdated, jurisdiction-specific to other states, or simply wrong for Oregon. DEQ and county rules are the authoritative source.</li>
          <li><strong>Confirm rules before buying equipment:</strong> A composting toilet system that is not approved by the county or that does not address graywater adequately is a system that the building inspector may require to be replaced before occupancy is approved. Confirming what is allowed before purchasing equipment is far less expensive than discovering a conflict during the permit process.</li>
        </ul>

        <div class="warning-box reveal-up">
          <div class="warning-box__icon" aria-hidden="true">
            <i data-lucide="alert-circle"></i>
          </div>
          <div class="warning-box__body">
            <strong>A composting toilet may reduce blackwater, but it does not automatically solve every wastewater issue.</strong>
            <p>Showers, sinks, laundry, and kitchen drains still need to be handled legally and safely. Graywater is still regulated in Oregon, and a permit may still be required. Confirm current requirements with Oregon DEQ and your county's environmental health department before purchasing equipment or designing around this approach.</p>
          </div>
        </div>

        <!-- ── COMMON MISTAKES ────────────────────────────────────── -->
        <h2 id="common-mistakes">Common Septic Mistakes on Off-Grid Properties</h2>

        <p>
          These are the mistakes that come up most often on rural Eastern Oregon builds. Most of them are preventable with early planning — and expensive to correct after they become apparent.
        </p>

        <ul>
          <li><strong>Buying land before checking septic feasibility:</strong> A parcel with shallow soil over bedrock, high seasonal groundwater, or insufficient level area for a drain field may be very difficult or very expensive to permit for a full-time home. Checking septic feasibility before signing a purchase agreement is far less costly than discovering the issue afterward.</li>
          <li><strong>Choosing the home site before running a site evaluation:</strong> The home location should follow from where the site evaluation confirms the drain field can go — not the other way around. Committing to a home site before the drain field location is confirmed regularly forces expensive redesigns.</li>
          <li><strong>Forgetting the replacement drain field area:</strong> The primary drain field is half the story. The replacement area must be identified and preserved. On constrained parcels, it can occupy more land than the primary field. Many buyers do not factor the replacement area into their mental picture of how the site lays out.</li>
          <li><strong>Placing driveways, shops, or wells where the septic area needs to go:</strong> Once a driveway is cut or a foundation is poured over the replacement drain field area, the problem is expensive to resolve. Mapping all of these together on paper before breaking ground prevents the conflict entirely.</li>
          <li><strong>Assuming an old system can support a larger home:</strong> An existing septic system permitted for a two-bedroom cabin is not automatically sufficient for a three- or four-bedroom home. Increasing bedroom count typically requires enlarging the system — and the parcel needs space for that expansion.</li>
          <li><strong>Adding bedrooms without checking system capacity:</strong> A remodel that adds a bedroom — or a garage conversion that creates additional sleeping space — may require a septic system upgrade. Check before you design.</li>
          <li><strong>Assuming composting toilets eliminate permitting concerns:</strong> As covered above, they often do not. Graywater still needs to be addressed, and the approval process still applies.</li>
          <li><strong>Ignoring slope, drainage, rock, or high groundwater:</strong> These site conditions dramatically affect what system types are possible and how much they cost. They are not problems that go away — they need to be addressed in the system design.</li>
          <li><strong>Waiting too long to involve a builder:</strong> A builder familiar with Eastern Oregon conditions can help identify site constraints early, coordinate septic, well, driveway, and home placement together, and sequence the trades effectively. That perspective is most valuable before commitments are made — not after.</li>
        </ul>

